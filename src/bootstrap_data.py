"""Recreate the local remote from the deterministic source, verify its DVC hash."""
import hashlib
from pathlib import Path
import tempfile
import yaml
from src.generate_data import generate

if __name__ == "__main__":
    pointer = yaml.safe_load(Path("data/churn.csv.dvc").read_text())["outs"][0]
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / "churn.csv"
        generate(path)
        digest = hashlib.md5(path.read_bytes()).hexdigest()
        if digest != pointer["md5"]:
            raise RuntimeError("Generated bytes differ from the committed DVC data version")
        remote = Path("dvc-remote/files/md5") / digest[:2] / digest[2:]
        remote.parent.mkdir(parents=True, exist_ok=True)
        remote.write_bytes(path.read_bytes())
    print("Verified local DVC remote populated; run dvc pull")
